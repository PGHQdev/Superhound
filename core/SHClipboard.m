}
- (NSUInteger)count {return _items.count;}
- (BOOL)addText:(NSString *)text types:(NSArray<NSString *> *)types application:(NSString *)bundleID source:(NSString *)source {
 // Password managers mark their copies with these types (nspasteboard.org).
 NSSet *concealed=[NSSet setWithArray:@[@"org.nspasteboard.ConcealedType",@"org.nspasteboard.TransientType",@"org.nspasteboard.AutoGeneratedType",@"com.agilebits.onepassword"]];
 if(!text.length || text.length>Longest || ![text stringByTrimmingCharactersInSet:NSCharacterSet.whitespaceAndNewlineCharacterSet].length || [concealed intersectsSet:[NSSet setWithArray:types?:@[]]] || [@[@"com.apple.keychainaccess",@"com.apple.Passwords"] containsObject:bundleID])return NO;
 NSUInteger old=[_items indexOfObjectPassingTest:^BOOL(NSDictionary *item,NSUInteger i,BOOL *stop){(void)i;(void)stop;return [item[@"text"] isEqual:text];}];
