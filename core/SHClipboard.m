}
- (void)removeID:(NSString *)identifier {
 NSUInteger i=[_items indexOfObjectPassingTest:^BOOL(NSDictionary *item,NSUInteger index,BOOL *stop){(void)index;(void)stop;return [[NSString stringWithFormat:@"clipboard:%@",item[@"id"]] isEqual:identifier];}];
