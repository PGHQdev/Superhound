}
- (NSArray<NSDictionary *> *)search:(NSString *)query limit:(NSUInteger)limit {
 NSMutableArray *terms=NSMutableArray.array;for(NSString *t in [SHFold(query) componentsSeparatedByCharactersInSet:NSCharacterSet.whitespaceAndNewlineCharacterSet])if(t.length)[terms addObject:t];
 NSMutableArray *results=NSMutableArray.array;
 for(NSUInteger i=0;i<_items.count && results.count<limit;i++){
  BOOL match=YES;for(NSString *t in terms)if(![_folded[i] containsString:t]){match=NO;break;}
  if(!match)continue;
  NSDictionary *item=_items[i];NSString *text=item[@"text"],*path=[NSString stringWithFormat:@"clipboard:%@",item[@"id"]];
  [results addObject:@{@"type":@"clipboard",@"id":path,@"path":path,@"name":Title(text),@"copy":text,@"date":item[@"date"]?:@0,@"source":item[@"source"]?:@""}];
 }
